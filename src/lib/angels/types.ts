/**
 * The Angels & Demons world — contracts for the static JSON under public/angels/.
 * Everything is drawn as scripture actually speaks: every band, name, and title
 * carries verified refs; quotes are verbatim WEB (or Charles 1917 where noted).
 */

/** How directly a claim belongs to the cited text rather than a later synthesis. */
export type EvidenceStatus =
  | "explicit"
  | "inferred"
  | "disputed"
  | "tradition"
  | "extra-canonical";

export type Evidence = {
  status: EvidenceStatus;
  note: string;
};

/** One band of the throne→abyss ladder. */
export type OrderBand = {
  id: string;
  name: string;
  realm: "throne" | "heavens" | "earth" | "deep";
  line: string;
  refs: string[];
  evidence: Evidence;
};

/** A link into another room of this world — an order band, a fall step, an encounter. */
export type SeeAlso = { label: string; href: string };

/** An angel scripture names (plus the Angel of the LORD as a special case). */
export type NamedAngel = {
  name: string;
  meaning: string;
  line: string;
  quote: string;
  quoteRef: string;
  refs: string[];
  canonNote?: string;
  seeAlso?: SeeAlso;
};

/** A title scripture gives the enemy. */
export type EnemyName = {
  title: string;
  ref: string;
  quote: string;
};

export type OrderData = {
  bands: OrderBand[];
  named: NamedAngel[];
  enemyNames: EnemyName[];
};

/** A demon scripture actually names — distinct from Satan's own titles. */
export type NamedDemon = {
  id: string;
  name: string;
  altNames: string[];
  meaning: string;
  line: string;
  quote: string;
  quoteRef: string;
  refs: string[];
  canonNote?: string;
  seeAlso?: SeeAlso;
};

export type DemonsData = {
  demons: NamedDemon[];
};

/** One step of the fall, traced text by text. */
export type FallStep = {
  id: string;
  title: string;
  cite: string;
  /** Site-format ref when the text is hosted here; empty for external sources. */
  ref: string;
  quote: string;
  /** A paired second passage, when the step IS a comparison (census, Lucifer). */
  second?: { cite: string; ref: string; quote: string };
  note: string;
  sourceUrl?: string;
  /** A link into the full hosted text, when one exists on this site. */
  readMore?: SeeAlso;
  evidence: Evidence;
};

export type FallData = {
  steps: FallStep[];
};

/** An angel encounter. */
export type Appearance = {
  ref: string;
  who: string;
  event: string;
  line: string;
  quote?: string;
  seeAlso?: SeeAlso;
};

/** A Gospel exorcism episode (one entry per event; parallels listed). */
export type Exorcism = {
  ref: string;
  parallels: string[];
  place: string;
  event: string;
  /** What the demons said — verbatim WEB; empty when they were silenced. */
  theySaid: string;
  line: string;
  seeAlso?: SeeAlso;
};

export type EncountersData = {
  appeared: Appearance[];
  castOut: Exorcism[];
};

/** A doctrinal teaching about angels/demons from scripture. */
export type TeachingEntry = {
  id: string;
  title: string;
  ref: string;
  quote: string;
  line: string;
};

export type TeachingData = {
  entries: TeachingEntry[];
};

/**
 * The vocabulary of the unseen — public/angels/lexicon.json, generated by
 * scripts/angels/build-lexicon.mjs from the hosted original-language text.
 * Every count is a token count in the tagged Hebrew or Greek; the only
 * hand-written fields are the seed's headword, gloss, and one-line note.
 */
export type LexiconLang = "hebrew" | "greek";

export type LexiconOccurrence = {
  book: string;
  chapter: number;
  /** Which hosted edition carried the tokens: oshb, sblgnt, or lxx. */
  edition: string;
  verses: number[];
  count: number;
};

export type LexiconTerm = {
  id: string;
  group: string;
  lang: LexiconLang;
  /** Lemmas exactly as the hosted morphology tags them; empty for a phrase. */
  lemmas: string[];
  /** A two-lemma phrase counted when both sit within two tokens. */
  phrase?: [string, string];
  headword: string;
  transliteration: string;
  gloss: string;
  note: string;
  /** The term's counterpart in the other language, when one exists. */
  pair?: string;
  tokens: number;
  books: number;
  chapters: LexiconOccurrence[];
};

export type LexiconGroup = {
  id: string;
  title: string;
  lane: "holy" | "fallen";
  note: string;
};

export type LexiconData = {
  source: { originals: string; snapshot: string; editions: string[]; method: string };
  groups: LexiconGroup[];
  terms: LexiconTerm[];
  totals: { terms: number; tokens: number; chapters: number };
};

/** One Angels & Demons record that cites a chapter. */
export type UnseenRecordEntry = {
  kind: "order" | "named" | "title" | "demon" | "fall" | "encounter" | "exorcism" | "teaching";
  label: string;
  room: string;
  href: string;
};

/** What the reverse index knows about one hosted chapter. */
export type UnseenChapter = {
  entries: UnseenRecordEntry[];
  terms: { id: string; headword: string; lang: LexiconLang; count: number }[];
};

export type ChapterIndexData = {
  source: { records: string[]; lexicon: string };
  totals: { chapters: number; withRecords: number; withTerms: number };
  chapters: Record<string, UnseenChapter>;
};
