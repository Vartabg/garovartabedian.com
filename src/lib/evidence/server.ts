/**
 * Server-side How We Know data. This world keeps its cross-world claim tests
 * and provenance map in a separate public namespace, so analysis can point
 * back to other worlds without silently altering their source datasets.
 */

import evidenceJson from "../../../public/evidence/cases.json";
import claimsJson from "../../../public/meta/claims.json";
import type { ClaimRegistry } from "./claims";
import type { EvidenceData } from "./types";

export const getEvidenceData = (): EvidenceData =>
  evidenceJson as EvidenceData;

/**
 * The one registry every graded pill on the site reads. Generated by
 * scripts/site/build-claims.mjs from the rooms' own data, so it cannot say
 * something a room does not.
 */
export const getClaimRegistry = (): ClaimRegistry => claimsJson as ClaimRegistry;
